/*
utility function to verify the marking results based on a few criterions
1. Check if the title, category and instructions are matched
2. Check if the number of questions is correct
3. Check if the question types of each questions are valid
NOTE: This function does not check the content of the questions and options
as it is assumed that the marking results are generated by the AI model and
the content should be correct. This function only checks the structure of the
marking results to ensure that it is valid and students are not uploading an entirely different exercise.
*/

import { IExerciseContentJsonData } from "@acessment/generator-panel";

export function verifyMarkingResults(markingResults: IExerciseContentJsonData, exerciseJson: IExerciseContentJsonData) {
    // 1. Check if the title are matched
    if (
        markingResults.title !== exerciseJson.title
    ) {
        console.log("Title, category or instruction does not match.");
        return false;
    }

    // 2. Check if the number of questions is correct
    if (markingResults.questions.length !== exerciseJson.questions.length) {
        console.log("Number of questions does not match.");
        return false;
    }

    // 3. Check if the question types of each questions are valid
    for (let i = 0; i < markingResults.questions.length; i++) {
        if (markingResults.questions[i].type !== exerciseJson.questions[i].type) {
            console.log(`Question ${i + 1} type does not match.`);
            return false;
        }
    }
    return true;

    //TODO: Add more verification if needed, e.g. check the questions, options every single field etc.
}

export function sanitizeMarkingResults(markingResults: IExerciseContentJsonData, exercise_json: IExerciseContentJsonData): IExerciseContentJsonData {
    // This function is to ensure marking results matched with the exercise_json structure
    // Feel free to add more fields if needed
    return {
        ...markingResults,
        category: exercise_json.category
    };
}